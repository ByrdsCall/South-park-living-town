package com.hunt3r.southparktown

/**
 * SaveKeys — the save-key registry (Restructure Order Part 8.1,
 * Phase 3). Every key the game persists is declared exactly
 * once, here, with its ONE owning module, its value kind, its
 * cap (-1 = no single numeric cap; bounded by content or by a
 * registry named in the note) and its default/decoding note.
 *
 * Three key spaces:
 *  - STORE: the SaveStore-level keys Prefs reads and writes.
 *    Prefs refers to these ONLY through the consts below — the
 *    suite fails if a raw store-key literal reappears in
 *    Prefs.kt, and a runtime sweep over the whole Prefs API
 *    must touch exactly this set.
 *  - DOC: the top level of the game_state document. encode /
 *    decode keep their literals (one writer, one reader, both
 *    in Prefs.kt) and the suite pins both directions against
 *    this list: the encoded key set equals DOC, and every
 *    doc["..."] read in Prefs.kt is registered here.
 *  - GROUPS: the nested key groups inside doc values and
 *    inside the npc_memory doc, addressed by path ({} = an
 *    open map's value, [] = a list element). A group marked
 *    open has dynamic keys by design (names, times, ids) and
 *    declares no fixed key set.
 *
 * A key string NEVER changes once shipped — save compatibility
 * is load-bearing (the Phase 0 pre-split fixture round-trips
 * byte-identically through this registry). New keys are added
 * here first; the build fails until the registry, the writer
 * and the reader agree. Dead keys are retired only by the
 * Phase 11 purge, on the evidence of docs/SAVE_KEY_AUDIT.md.
 */
