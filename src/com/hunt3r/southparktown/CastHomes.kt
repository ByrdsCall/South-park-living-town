//     the bus itself, and Lucky's rule is that NOBODY
//     defaults to the Bus Stop. The school bus sleeps at
//     the school; its driver anchors at the Elementary.
//
// This is derived data, never save state: the map is a
// pure function of the cast tables, so it cannot drift
// out of a save or be corrupted by one. The suite pins
// the table whole: every cast id mapped exactly once,
// every target a real location, no Bus Stop anywhere,
// and the residence rows equal to the family-house
// table's own rows.
// ============================================================

